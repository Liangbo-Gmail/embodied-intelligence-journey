# 练习2：用 np.linalg.svd 分解 AᵀA，观察 U 的列向量
#        再用 np.linalg.eig 求 AᵀA 的特征向量，对比两者
# （呼应第 2 课：AᵀA 是对称矩阵，U 应该和特征向量一致，最多差正负号）
# ============================================================
AtA = A.T @ A

U, sigma, Vt = np.linalg.svd(AtA)
eigenvalues, eigenvectors = np.linalg.eig(AtA)
print("SVD 的 U =\n", U)
print("eig 的特征向量 =\n", eigenvectors)
